import type { Metadata, Viewport } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { Providers } from "@/components/providers";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Meadow",
  description: "Personal finance tracking, budgeting, and investment allocation.",
};

// viewportFit: "cover" lets the PWA's content draw under the iOS home-
// indicator/notch area -- without it, env(safe-area-inset-*) (used by
// MobileTabbar below) always resolves to 0, so the fixed bottom tab bar
// would sit flush against the edge with no clearance from the home
// indicator on notched devices.
export const viewport: Viewport = {
  viewportFit: "cover",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      suppressHydrationWarning
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <Providers>{children}</Providers>
      </body>
    </html>
  );
}
